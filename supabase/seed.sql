    values (pr.id, 1, 'Baseline v1', 'Initial approved baseline (DEMO)', 'draft', pr.manager) returning id into v_rev;

    update _sa s set wd = (
      select count(*) from generate_series(pr.start_date + s.s_off, pr.start_date + s.f_off, interval '1 day') g
      where extract(dow from g)::int = any (pr.weekdays)
        and not exists (select 1 from public.project_holidays h where h.project_id = pr.id and h.holiday_date = g::date)
    ) where s.pidx = pr.idx;

