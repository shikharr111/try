        v_qty := least(round(v_rate * sa.perf * v_noise, 2), sa.qty - v_cum);

        -- demo weather/material shocks that really reduce output on those days
        if extract(doy from d)::int % 11 = 0 and sa.pidx = 1 then v_qty := round(v_qty * 0.55, 2); end if;
        if v_qty <= 0 then continue; end if;

